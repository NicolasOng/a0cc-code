def game_data_to_training_set(game_data: GameData) -> list[ExperienceData]:
    '''
    Converts a game data object generated by a game into a training set.
    Each turn in the game data is transformed into a training example.
    '''
    training_set: list[ExperienceData] = []
    # get the game data and transform it into training data
    game_winner = game_data.winner
    
    turn_data = game_data.turn_data
    for turn in turn_data:
        # get the board state
        board = turn.board

        # get the mask for full legal moves
        legal_move_mask = get_legal_move_mask_from_state(board, for_model=True)

        # get the outcome of the game for the current player
        current_player = board.current_player
        if game_winner is None:
            # draws and unfinished games
            value = 0.0
        else:
            # 1 for win, -1 for loss
            # based on the perspective of the current player
            value = 1.0 if game_winner == current_player else -1.0
        
        # get the policy distribution generated by MCTS (already np from Policy class)
        mcts_policy = turn.player_data

        # create a training example
        training_example: ExperienceData = ExperienceData(
            board=board_to_input(board),
            value=value,
            policy=mcts_policy,
            mask=legal_move_mask
        )
        
        # add it to the training set
        training_set.append(training_example)

    return training_set

def game_data_to_gt_training_set(game_data: GameData) -> list[ExperienceData]:
    '''
    Converts a game data object generated by a game into a training set.
    Each turn in the game data is transformed into a training example.
    Except this function uses the ground truth data for the value/policy at each state,
    rather than the "experienced" outcome/policy.
    '''
    gt = GroundTruth()
    training_set: list[ExperienceData] = []
    
    turn_data = game_data.turn_data
    for turn in turn_data:
        # get the board state
        board = turn.board

        # get the mask for full legal moves
        legal_move_mask = get_legal_move_mask_from_state(board, for_model=True)

        # get the gt outcome of the board for the current player
        value = gt.get_outcome(board)
        
        # get the gt policy distribution (list[float] from GroundTruth, needs np conversion)
        mcts_policy = np.array(gt.get_1ply_policy_prob_dist_list(board, for_model=True), dtype=np.float32)

        # create a training example
        training_example: ExperienceData = ExperienceData(
            board=board_to_input(board),
            value=value,
            policy=mcts_policy,
            mask=legal_move_mask
        )
        
        # add it to the training set
        training_set.append(training_example)

    return training_set

def _play(serialized_player: bytes) -> tuple[list[ExperienceData], GameData]:
    '''
    Plays a game of chinese checkers with the given players,
    then converts the game data into a training set.
    This function returns both the training set and the game data.
    '''
    # first, set up logging (since this is a separate process)
    setup_logging(
        level=20,
        log_dir=config.log_dir,
        process_name="training_alphazero"
    )
    # then play the game
    game_has_reverse_moves = config.backwards_moves
    game_has_side_moves = config.sideways_moves
    if config.root_game_has_all_moves:
        game_has_reverse_moves = True
        game_has_side_moves = True
    game = Game(
        board_size=config.board_size,
        num_pieces=config.num_pieces,
        repeats_for_draw=config.repeats_for_draw,
        no_reverse_moves=not game_has_reverse_moves,
        no_illegal_moves=not config.illegal_moves,
        no_side_moves=not game_has_side_moves
    )
    player: A0Player = dill.loads(serialized_player)
    game_data = play(game, [player, player], config.turn_limit)

    if config.use_gt:
        return game_data_to_gt_training_set(game_data), game_data
    else:
        return game_data_to_training_set(game_data), game_data

def self_play(player: A0Player) -> tuple[list[ExperienceData], list[GameData]]:
    '''
    Runs self-play to generate a training set for the AlphaZero model.
    This function uses multiprocessing to run multiple games in parallel.
    The training set is generated from the game data, which is then returned.
    The game data can also be saved to a file if a filepath is provided.
    Args:
        player (A0Player): The player to use for self-play.
    Returns:
        The generated training set, containing board states, values, and policies.
        The game data for each game played, which can be used for analysis or debugging.
    '''
    logger.info("Starting self-play to generate training data...")
    # serialize the player model (JAX models cannot be pickled directly + serialization is needed for multiprocessing)
    player_serialized: bytes = dill.dumps(player)
    # use self-play with the model and mcts to generate training data
    # run each game in parallel
    game_data_list: list[GameData] = []
    training_set: list[ExperienceData] = []
    num_cores = config.num_workers
    logger.info(f"Using {num_cores} cores for self-play.")
    with concurrent.futures.ProcessPoolExecutor() as executor:
        # create a list to hold the futures
        futures: list[Future[tuple[list[ExperienceData], GameData]]] = []

        # create a function to start a game
        def start_game() -> None:
            future = executor.submit(
                _play,
                serialized_player=player_serialized
            )
            futures.append(future)
        
        # start a game for each core
        for _ in range(num_cores):
            start_game()
        
        while True:
            logger.info(f"Current training set size: {len(training_set)}/{config.training_samples}")
            # when a game (or games) finish(es),
            done, _ = wait(futures, return_when=FIRST_COMPLETED)

            # for each finished game,
            for future in done:
                # remove it from the list of futures
                futures.remove(future)
                # get the training data and game data from the game
                game_training_set, game_data = future.result()
                # add the training data to the training set
                training_set.extend(game_training_set)
                # and the game data to the list of game data
                game_data_list.append(game_data)
                # if the training set is not full yet, start a new game
                if len(training_set) < config.training_samples:
                    start_game()
            
            # stop when the training set is full
            if len(training_set) >= config.training_samples:
                logger.info("Training set is full, cancelling all games.")
                # cancel any submitted but not yet started games
                for future in futures:
                    future.cancel()
                # note the following does not immediately stop all processes,
                # but prevents new tasks from being started
                # and frees this main process to continue
                # the remaining games/processes finish in the background
                # executor.shutdown(wait=False)
                break
    
    logger.info(f"Generated training set of size: {len(training_set)}/{config.training_samples}")
    return training_set, game_data_list

def get_most_recent_model_path() -> Optional[tuple[str, int]]:
    '''
    Returns the path to the most recent model in the training directory,
    along with its iteration number.
    If no models are found, returns None.
    '''
    if not config.training_dir:
        return None
    model_files = [
        f for f in os.listdir(config.training_dir)
        if f.startswith("model_") and f.endswith(".pkl")
    ]
    if not model_files:
        return None
    # get the model with the highest iteration number
    max_iteration = -1
    most_recent_model_file = ""
    for f in model_files:
        iteration_str = f[len("model_"):-len(".pkl")]
        try:
            iteration = int(iteration_str)
            if iteration > max_iteration:
                max_iteration = iteration
                most_recent_model_file = f
        except ValueError:
            continue
    if max_iteration == -1:
        return None
    return (os.path.join(config.training_dir, most_recent_model_file), max_iteration)

def train_alphazero() -> None:
    os.makedirs(config.plot_dir + "training_plots", exist_ok=True)

    most_recent_model = get_most_recent_model_path()
    if most_recent_model is not None:
        model_path, starting_iteration = most_recent_model
        logger.info(f"Resuming training from model: {model_path} at iteration {starting_iteration}")
    else:
        model_path = None
        starting_iteration = 0
        logger.info("Starting new training from scratch.")
    
    if model_path:
        model = load_model(model_path)
    else:
        model = AlphaZeroModel(
            config.board_size,
            rngs=nnx.Rngs({'params': jax.random.PRNGKey(0)})
        )
        save_model(config.training_dir + f'/model_{0}.pkl', model)
    
    experience_buffer = ExperienceBuffer(
        config.replay_buffer_size
    )

    iterations = config.training_iterations
    train_datas: list[DatasetData] = []
    logger.log(25, GameDataStats.get_header())
    for i in range(starting_iteration, iterations):
        print(f"Iteration {i + 1}/{iterations}")
        logger.info(f"Iteration {i + 1}/{iterations}")
        # create a player with the current model
        player = A0Player(
            config.board_size,
            config.num_pieces,
            model,
            mcts_samples=config.mcts_samples,
            no_reverse_moves=not config.backwards_moves,
            no_illegal_moves=not config.illegal_moves,
            no_side_moves=not config.sideways_moves,
            rollout_type=config.rollout_type,
            rollout_depth=config.rollout_depth,
            policy_type=config.policy_type,
            epsilon=config.epsilon,
            dirichlet_epsilon=config.dirichlet_epsilon
        )

        # generate training data with self-play
        training_set, game_data = self_play(player)

        # generate and print stats about the game data
        game_data_stats = game_data_list_stats(i, game_data)
        logger.log(25, f"{game_data_stats.get_line()}")
        
        # save the game data to a file
        if config.training_dir:
            with open(config.training_dir + f"gamedata_{i + 1}.pkl", 'wb') as f:
                pickle.dump(game_data, f)
        
        # add the training data to the replay buffer
        for example in training_set:
            experience_buffer.add(example)
        
        # train the model on the experiences in the replay buffer
        model, train_data = train_model_epochs(
            model=model,
            dataset=experience_buffer.get_dataset(config.training_batch_size),
            num_epochs=1,
            save="none",
            plot=False,
            test_datasets={}
        )
        train_datas.append(train_data)

        # plot, log, and save the model performance metrics in this iteration's training
        plot_model_performance(f"training_plots/iteration_{i + 1}", [train_data])
        save_dataset_data(
            f"{config.training_dir}/iteration_stats_{i + 1}.pkl",
            train_data
        )
        total, value_loss, policy_loss, value_accuracy, policy_accuracy = stats_from_dataset_data(train_data)
        logger.log(25, f"Iteration {i + 1} stats: Total Loss: {total:.4f}, Value Loss: {value_loss:.4f}, Policy Loss: {policy_loss:.4f}, Value Accuracy: {value_accuracy:.2%}, Policy Accuracy: {policy_accuracy:.2%}")

        # save the model after each iteration
        if config.training_dir:
            save_model(config.training_dir + f'model_{i + 1}.pkl', model)
    
    # after all iterations, plot all the training data
    plot_model_performance("training_plots/full_a0", train_datas)

if __name__ == "__main__":
    setup_logging(
        level=20,
        log_dir=config.log_dir,
        process_name="training_alphazero"
    )

    logger.info(f"config: {config.path}")

    # Set the multiprocessing start method to 'spawn' for compatibility with JAX
    try:
        multiprocessing.set_start_method('spawn')
    except RuntimeError:
        pass

    # Example usage
    train_alphazero()
