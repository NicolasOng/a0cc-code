def game_data_to_training_set(game_data: GameData) -> list[ExperienceData]:
    '''
    Converts a game data object generated by a game into a training set.
    Each turn in the game data is transformed into a training example.
    '''
    training_set: list[ExperienceData] = []
    # get the game data and transform it into training data
    game_winner = game_data.winner
    
    turn_data = game_data.turn_data
    for turn in turn_data:
        # get the board state
        board = turn.board

        # get the mask for full legal moves
        legal_move_mask = get_legal_move_mask_from_state(board, for_model=True)

        # get the outcome of the game for the current player
        current_player = board.current_player
        if game_winner is None:
            # draws and unfinished games
            value = 0.0
        else:
            # 1 for win, -1 for loss
            # based on the perspective of the current player
            value = 1.0 if game_winner == current_player else -1.0
        
        # get the policy distribution generated by MCTS (already np from Policy class)
        mcts_policy = turn.player_data

        # create a training example
        training_example: ExperienceData = ExperienceData(
            board=board_to_input(board),
            value=value,
            policy=mcts_policy,
            mask=legal_move_mask
        )
        
        # add it to the training set
        training_set.append(training_example)

    return training_set

def game_data_to_gt_training_set(game_data: GameData, gt: GroundTruth | None = None) -> list[ExperienceData]:
    '''
    Converts a game data object generated by a game into a training set.
    Each turn in the game data is transformed into a training example.
    Except this function uses the ground truth data for the value/policy at each state,
    rather than the "experienced" outcome/policy.
    '''
    if gt is None:
        gt = GroundTruth()
    training_set: list[ExperienceData] = []
    
    turn_data = game_data.turn_data
    for turn in turn_data:
        # get the board state
        board = turn.board

        # get the mask for full legal moves
        legal_move_mask = get_legal_move_mask_from_state(board, for_model=True)

        # get the gt outcome of the board for the current player
        value = gt.get_outcome(board)
        
        # get the gt policy distribution (list[float] from GroundTruth, needs np conversion)
        mcts_policy = np.array(gt.get_1ply_policy_prob_dist_list(board, for_model=True), dtype=np.float32)

        # create a training example
        training_example: ExperienceData = ExperienceData(
            board=board_to_input(board),
            value=value,
            policy=mcts_policy,
            mask=legal_move_mask
        )
        
        # add it to the training set
        training_set.append(training_example)

    return training_set

def game_data_to_gt_value_training_set(game_data: GameData, gt: GroundTruth | None = None) -> list[ExperienceData]:
    '''
    Like game_data_to_training_set, but replaces the value with the ground truth
    outcome of the current state. The policy is kept as the MCTS policy.
    '''
    if gt is None:
        gt = GroundTruth()
    training_set: list[ExperienceData] = []

    turn_data = game_data.turn_data
    for turn in turn_data:
        board = turn.board
        legal_move_mask = get_legal_move_mask_from_state(board, for_model=True)

        # GT value for the current state
        value = gt.get_outcome(board)

        # MCTS policy (already in model perspective)
        mcts_policy = turn.player_data

        training_example = ExperienceData(
            board=board_to_input(board),
            value=value,
            policy=mcts_policy,
            mask=legal_move_mask
        )
        training_set.append(training_example)

    return training_set

def game_data_to_gt_next_value_training_set(game_data: GameData, gt: GroundTruth | None = None) -> list[ExperienceData]:
    '''
    Like game_data_to_training_set, but replaces the value with the ground truth
    outcome of the next state, where the top action in the MCTS policy is taken
    on the current state. The policy is kept as the MCTS policy.
    The GT outcome of the next state is from the opponent's perspective,
    so it is negated to stay in the current player's perspective.
    '''
    if gt is None:
        gt = GroundTruth()
    training_set: list[ExperienceData] = []

    turn_data = game_data.turn_data
    for turn in turn_data:
        board = turn.board
        legal_move_mask = get_legal_move_mask_from_state(board, for_model=True)

        # The stored MCTS policy is in model perspective (rotated for PLAYER_O).
        # Un-rotate to find the actual best move on the board.
        mcts_policy = turn.player_data
        p = Policy(len(board.board))
        p.set_logits(mcts_policy.copy(), rotate_180=False)
        if board.current_player == Player.PLAYER_O:
            p.rotate_policy()
        best_move = p.get_best_move()

        # Apply the best move to get the next state
        board.apply_move(best_move)
        # GT outcome from the next state's current player (opponent), negated
        value = -gt.get_outcome(board)
        board.undo_move(best_move)

        training_example = ExperienceData(
            board=board_to_input(board),
            value=value,
            policy=mcts_policy,
            mask=legal_move_mask
        )
        training_set.append(training_example)

    return training_set

def game_data_to_model_value_training_set(game_data: GameData, model: AlphaZeroModel | MultiTrunkAlphaZeroModel) -> list[ExperienceData]:
    '''
    Like game_data_to_training_set, but uses backward-propagated model values as targets.
    The last state's target is the true game outcome. For all earlier states, the target
    is the negated model value of the next state (negated because players alternate).
    The policy is kept as the MCTS policy.
    Also populates turn.alternative_value_target
    the model's predictions are saved with the game data.
    '''
    training_set: list[ExperienceData] = []

    turn_data = game_data.turn_data
    if not turn_data:
        return training_set

    # batch all board inputs for a single inference call
    board_inputs = [board_to_input(turn.board) for turn in turn_data]
    boards = np.concatenate(board_inputs, axis=0)
    model_values, _ = model.inference(boards)
    model_values = jax.lax.stop_gradient(model_values)

    # compute targets backward from the last state
    num_turns = len(turn_data)
    targets = [0.0] * num_turns

    # last state: true game outcome from that player's perspective
    game_winner = game_data.winner
    if game_winner is None:
        targets[-1] = 0.0
    else:
        targets[-1] = 1.0 if game_winner == turn_data[-1].board.current_player else -1.0

    # earlier states: negated model value of the next state
    for t in range(num_turns - 2, -1, -1):
        targets[t] = -float(model_values[t + 1][0])

    for turn, board_input, target in zip(turn_data, board_inputs, targets):
        turn.alternative_value_target = target

        legal_move_mask = get_legal_move_mask_from_state(turn.board, for_model=True)
        training_example = ExperienceData(
            board=board_input,
            value=target,
            policy=turn.player_data,
            mask=legal_move_mask
        )
        training_set.append(training_example)

    return training_set

def game_data_to_td_lambda_training_set(game_data: GameData, model: AlphaZeroModel | MultiTrunkAlphaZeroModel, lam: float) -> list[ExperienceData]:
    '''
    Uses TD(lambda) targets to blend bootstrapped and Monte Carlo returns.
      - lambda=0: TD(0), target = -V(s_{t+1})
      - lambda=1: Monte Carlo, target = game outcome
    Recursive formula (backward pass):
      G_{T-1} = z_{T-1}
      G_t     = -(1 - lambda) * V[t+1] - lambda * G_{t+1}
    The policy is kept as the MCTS policy.
    '''
    training_set: list[ExperienceData] = []
    turn_data = game_data.turn_data
    if not turn_data:
        return training_set

    # \hat{v}(S_0), \hat{v}(S_1), ..., \hat{v}(S_{T-1}) via batch inference
    # pad to fixed batch size so JAX JIT only compiles one kernel for this path
    FIXED_BATCH_SIZE = config.turn_limit if config.turn_limit else 64
    board_inputs = [board_to_input(turn.board) for turn in turn_data]
    boards = np.concatenate(board_inputs, axis=0)
    num_real = boards.shape[0]
    if num_real < FIXED_BATCH_SIZE:
        padding = np.zeros((FIXED_BATCH_SIZE - num_real, *boards.shape[1:]), dtype=boards.dtype)
        boards_padded = np.concatenate([boards, padding], axis=0)
    else:
        boards_padded = boards
    model_values, _ = model.inference(boards_padded)
    model_values = model_values[:num_real]
    model_values = jax.lax.stop_gradient(model_values)

    num_turns = len(turn_data)
    targets = [0.0] * num_turns

    # G_{T-1}^\lambda = z_{T-1}   (game outcome from last player's perspective)
    game_winner = game_data.winner
    if game_winner is None:
        targets[-1] = 0.0
    else:
        targets[-1] = 1.0 if game_winner == turn_data[-1].board.current_player else -1.0

    # G_t^\lambda = -(1 - \lambda) \hat{v}(S_{t+1}) - \lambda G_{t+1}^\lambda
    # Both terms are negated because \hat{v}(S_{t+1}) and G_{t+1}^\lambda
    # are from the next player's (opponent's) perspective.
    for t in range(num_turns - 2, -1, -1):
        v_next = float(model_values[t + 1][0])  # \hat{v}(S_{t+1})
        targets[t] = -(1 - lam) * v_next - lam * targets[t + 1]

    for turn, board_input, target in zip(turn_data, board_inputs, targets):
        turn.alternative_value_target = target
        legal_move_mask = get_legal_move_mask_from_state(turn.board, for_model=True)
        training_example = ExperienceData(
            board=board_input,
            value=target,
            policy=turn.player_data,
            mask=legal_move_mask
        )
        training_set.append(training_example)

    return training_set

def capture_dataset_diagnostics(
    pre_balance_values: np.ndarray,
    post_balance_values: np.ndarray,
) -> dict[str, list[float]]:
    return {
        'dataset_values_pre': pre_balance_values.tolist(),
        'dataset_values_post': post_balance_values.tolist()
    }

def _play(serialized_player: bytes, cancel_event: Optional[Any] = None) -> tuple[list[ExperienceData], GameData]:
    '''
    Plays a game of chinese checkers with the given players,
    then converts the game data into a training set.
    This function returns both the training set and the game data.
    If cancel_event is provided, the game will exit early (between turns) when it is set.
    '''
    # first, set up logging (since this is a separate process)
    setup_logging(
        level=20,
        log_dir=config.log_dir,
        process_name="training_alphazero"
    )
    # then play the game
    game_has_reverse_moves = config.backwards_moves
    game_has_side_moves = config.sideways_moves
    if config.root_game_has_all_moves:
        game_has_reverse_moves = True
        game_has_side_moves = True
    game = Game(
        board_size=config.board_size,
        num_pieces=config.num_pieces,
        repeats_for_draw=config.repeats_for_draw,
        no_reverse_moves=not game_has_reverse_moves,
        no_illegal_moves=not config.illegal_moves,
        no_side_moves=not game_has_side_moves
    )
    player: A0Player = dill.loads(serialized_player)
    game_data = play(game, [player, player], config.turn_limit, cancel_event=cancel_event)

    if config.alternative_target == "gt":
        return game_data_to_gt_training_set(game_data), game_data
    elif config.alternative_target == "gt_value":
        return game_data_to_gt_value_training_set(game_data), game_data
    elif config.alternative_target == "gt_next_value":
        return game_data_to_gt_next_value_training_set(game_data), game_data
    elif config.alternative_target == "td_0":
        return game_data_to_model_value_training_set(game_data, player.model), game_data
    elif config.alternative_target == "td_lambda":
        lam = config.td_lambda
        return game_data_to_td_lambda_training_set(game_data, player.model, lam), game_data
    else:
        return game_data_to_training_set(game_data), game_data

def self_play(player: A0Player) -> tuple[list[ExperienceData], list[GameData]]:
    '''
    Runs self-play to generate a training set for the AlphaZero model.
    This function uses multiprocessing to run multiple games in parallel.
    The training set is generated from the game data, which is then returned.
    The game data can also be saved to a file if a filepath is provided.
    Args:
        player (A0Player): The player to use for self-play.
    Returns:
        The generated training set, containing board states, values, and policies.
        The game data for each game played, which can be used for analysis or debugging.
    '''
    logger.info("Starting self-play to generate training data...")
    # serialize the player model (JAX models cannot be pickled directly + serialization is needed for multiprocessing)
    player_serialized: bytes = dill.dumps(player)
    # use self-play with the model and mcts to generate training data
    # run each game in parallel
    game_data_list: list[GameData] = []
    training_set: list[ExperienceData] = []
    num_cores = config.num_workers
    logger.info(f"Using {num_cores} cores for self-play.")
    # Manager outlives the executor so the cancel_event proxy stays valid
    # until all worker processes have finished.
    with multiprocessing.Manager() as manager:
        cancel_event = manager.Event()
        with concurrent.futures.ProcessPoolExecutor(max_workers=num_cores, max_tasks_per_child=1) as executor:
            # create a list to hold the futures
            futures: list[Future[tuple[list[ExperienceData], GameData]]] = []

            # create a function to start a game
            def start_game() -> None:
                future = executor.submit(
                    _play,
                    serialized_player=player_serialized,
                    cancel_event=cancel_event
                )
                futures.append(future)

            # start a game for each core
            for _ in range(num_cores):
                start_game()

            while True:
                logger.info(f"Current training set size: {len(training_set)}/{config.training_samples}")
                # when a game (or games) finish(es),
                done, _ = wait(futures, return_when=FIRST_COMPLETED)

                # for each finished game,
                for future in done:
                    # remove it from the list of futures
                    futures.remove(future)
                    # get the training data and game data from the game
                    game_training_set, game_data = future.result()
                    # add the training data to the training set
                    training_set.extend(game_training_set)
                    # and the game data to the list of game data
                    game_data_list.append(game_data)
                    # if the training set is not full yet, start a new game
                    if len(training_set) < config.training_samples:
                        start_game()

                # stop when the training set is full
                if len(training_set) >= config.training_samples:
                    logger.info("Training set is full, cancelling all games.")
                    # signal already-running games to exit early (checked between turns)
                    cancel_event.set()
                    # cancel any submitted but not yet started games
                    for future in futures:
                        future.cancel()
                    # the executor's __exit__ will wait for running workers to finish,
                    # but they now bail out quickly thanks to cancel_event
                    break
    
    logger.info(f"Generated training set of size: {len(training_set)}/{config.training_samples}")
    return training_set, game_data_list

def get_most_recent_model_path() -> Optional[tuple[str, int]]:
    '''
    Returns the path to the most recent model in the training directory,
    along with its iteration number.
    If no models are found, returns None.
    '''
    if not config.training_dir:
        return None
    model_files = [
        f for f in os.listdir(config.training_dir)
        if f.startswith("model_") and f.endswith(".pkl")
    ]
    if not model_files:
        return None
    # get the model with the highest iteration number
    max_iteration = -1
    most_recent_model_file = ""
    for f in model_files:
        iteration_str = f[len("model_"):-len(".pkl")]
        try:
            iteration = int(iteration_str)
            if iteration > max_iteration:
                max_iteration = iteration
                most_recent_model_file = f
        except ValueError:
            continue
    if max_iteration == -1:
        return None
    return (os.path.join(config.training_dir, most_recent_model_file), max_iteration)

def train_alphazero(seed: int = 0, force_fresh: bool = False, attempt: int = 1) -> dict[str, Any]:
    """
    Returns a result dict:
      {"success": bool, "collapse_iteration": Optional[int], "value_pre_tanh_mean_abs": Optional[float]}
    On detected collapse, success=False and the other fields describe the trigger.
    When force_fresh=True, any existing model_*.pkl files in the training dir are
    removed and training starts from scratch with the provided seed.
    `attempt` is the 1-indexed retry number, stamped into the iteration-diagnostics
    jsonl so retries are distinguishable.
    """
    os.makedirs(config.plot_dir + "training_plots", exist_ok=True)
    diagnostics_log_path = config.log_dir + "iteration_diagnostics.jsonl"

    if force_fresh and os.path.isdir(config.training_dir):
        for f in os.listdir(config.training_dir):
            if f.startswith("model_") and f.endswith(".pkl"):
                os.remove(os.path.join(config.training_dir, f))
        logger.info(f"Fresh-start retry (seed={seed}); cleared prior model checkpoints.")
        most_recent_model = None
    else:
        most_recent_model = get_most_recent_model_path()

    if most_recent_model is not None:
        model_path, starting_iteration = most_recent_model
        logger.info(f"Resuming training from model: {model_path} at iteration {starting_iteration}")
    else:
        model_path = None
        starting_iteration = 0
        logger.info(f"Starting new training from scratch (seed={seed}).")

    if model_path:
        model = load_model(model_path)
    else:
        model = create_model(
            config.board_size,
            rngs=nnx.Rngs({'params': jax.random.PRNGKey(seed)})
        )
        save_model(config.training_dir + f'/model_{0}.pkl', model)
    
    random_states = get_random_states_no_gt(256)
    random_states, _ = remove_duplicates(random_states)
    rsrd = get_rd_from_states(random_states, 256, shuffle=True)
    
    experience_buffer = ExperienceBuffer(
        config.replay_buffer_size
    )

    iterations = config.training_iterations
    train_datas: list[DatasetData] = []
    logger.log(25, GameDataStats.get_header())
    for i in range(starting_iteration, iterations):
        print(f"Iteration {i + 1}/{iterations}")
        logger.info(f"Iteration {i + 1}/{iterations}")
        # create a player with the current model
        player = A0Player(
            config.board_size,
            config.num_pieces,
            model,
            mcts_samples=config.mcts_samples,
            no_reverse_moves=not config.backwards_moves,
            no_illegal_moves=not config.illegal_moves,
            no_side_moves=not config.sideways_moves,
            rollout_type=config.rollout_type,
            rollout_depth=config.rollout_depth,
            policy_type=config.policy_type,
            epsilon=config.epsilon,
            dirichlet_epsilon=config.dirichlet_epsilon
        )

        # generate training data with self-play
        training_set, game_data = self_play(player)

        # generate and print stats about the game data
        game_data_stats = game_data_list_stats(i, game_data)
        logger.log(25, f"{game_data_stats.get_line()}")
        
        # save the game data to a file
        if config.training_dir:
            with open(config.training_dir + f"gamedata_{i + 1}.pkl", 'wb') as f:
                pickle.dump(game_data, f)
        
        # add the training data to the replay buffer
        for example in training_set:
            experience_buffer.add(example)
        
        # get a dataset from the replay buffer for training, and train the model on it
        eb_dataset = experience_buffer.get_dataset(config.training_batch_size)
        # print the distribution of values in the dataset
        win_count, draw_count, loss_count = eb_dataset.get_distribution()
        logger.log(25, f"Training dataset distribution (pre-balancing): {win_count} wins, {draw_count} draws, {loss_count} losses")
        eb_dataset.print_bucket_distribution()
        pre_balance_values = eb_dataset.values.flatten().copy()
        
        if config.dataset_balance_method == "subsample_buckets":
            logger.log(25, f"Balancing values into {config.num_buckets_for_balance} buckets (win vs non-win)...")
            eb_dataset.balance_values_symmetric(n_buckets=config.num_buckets_for_balance)
            new_win_count, new_draw_count, new_loss_count = eb_dataset.get_distribution()
            logger.log(25, f"After balancing: {new_win_count} wins, {new_draw_count} draws, {new_loss_count} losses")
            eb_dataset.print_bucket_distribution()
        elif config.dataset_balance_method == "weighted_buckets":
            logger.log(25, f"Computing symmetric-pair value weights ({config.num_buckets_for_balance} buckets, max_ratio={config.max_weight_ratio})...")
            eb_dataset.compute_value_weights_symmetric(
                n_buckets=config.num_buckets_for_balance,
                max_weight_ratio=config.max_weight_ratio,
            )
        
        # capture dataset diagnostics: distributions before and after balancing
        post_balance_values = eb_dataset.values.flatten().copy()
        dataset_diagnostics = capture_dataset_diagnostics(
            pre_balance_values, post_balance_values
        )
        if config.training_dir:
            with open(config.training_dir + f"dataset_diagnostics_{i + 1}.pkl", 'wb') as f:
                pickle.dump(dataset_diagnostics, f)

        # train the model on the experiences in the replay buffer
        model, train_data = train_model_epochs(
            model=model,
            dataset=eb_dataset,
            num_epochs=1,
            save="none",
            plot=False,
            test_datasets={}
        )
        train_datas.append(train_data)

        # plot, log, and save the model performance metrics in this iteration's training
        plot_model_performance(f"training_plots/iteration_{i + 1}", [train_data])
        save_dataset_data(
            f"{config.training_dir}/iteration_stats_{i + 1}.pkl",
            train_data
        )
        total, value_loss, policy_loss, value_accuracy, policy_accuracy = stats_from_dataset_data(train_data)
        logger.log(25, f"Iteration {i + 1} stats: Total Loss: {total:.4f}, Value Loss: {value_loss:.4f}, Policy Loss: {policy_loss:.4f}, Value Accuracy: {value_accuracy:.2%}, Policy Accuracy: {policy_accuracy:.2%}")

        # save the model after each iteration
        if config.training_dir:
            save_model(config.training_dir + f'model_{i + 1}.pkl', model)

        # per-iteration diagnostics on the rsrd probe batch (always on, independent
        # of config.detect_collapse — the flag only gates the early-abort below).
        diagnostics = log_iteration_diagnostics(model, rsrd, diagnostics_log_path, attempt, i + 1)

        # early-abort on collapse — only in the danger window, only if enabled
        if config.detect_collapse and (i + 1) <= config.collapse_detection_iteration:
            pre_tanh_mean = diagnostics['per_site_stats']['value_pre_tanh']['mean_abs']
            if pre_tanh_mean > config.collapse_threshold_pre_tanh:
                logger.log(30, f"COLLAPSE DETECTED at iter {i + 1}: value_pre_tanh mean_abs {pre_tanh_mean:.2f} > threshold {config.collapse_threshold_pre_tanh}")
                return {"success": False, "collapse_iteration": i + 1, "value_pre_tanh_mean_abs": pre_tanh_mean}

        # free stale JIT caches and unreferenced GPU memory before the next iteration
        jax.clear_caches()
        gc.collect()

    # after all iterations, plot all the training data
    plot_model_performance("training_plots/full_a0", train_datas)
    return {"success": True, "collapse_iteration": None, "value_pre_tanh_mean_abs": None}

if __name__ == "__main__":
    setup_logging(
        level=20,
        log_dir=config.log_dir,
        process_name="training_alphazero"
    )

    logger.info(f"config: {config.path}")

    # Set the multiprocessing start method to 'spawn' for compatibility with JAX
    try:
        multiprocessing.set_start_method('spawn')
    except RuntimeError:
        pass

    # Background system-metrics logger (runs across all retry attempts). System-wide
    # metrics include all self-play workers, not just this process.
    metrics_logger: Optional[SystemMetricsLogger] = None
    if config.log_system_metrics:
        metrics_logger = SystemMetricsLogger(
            output_path=config.log_dir + "system_metrics.jsonl",
            interval_seconds=config.system_metrics_interval_seconds,
        ).start()
        logger.log(25, f"System metrics → {config.log_dir}system_metrics.jsonl (every {config.system_metrics_interval_seconds}s)")

    retry_log_path = config.log_dir + "retry_log.jsonl"

    try:
        # Retry loop: on detected collapse in the early-iteration window, restart
        # with a fresh model and a new seed. max_collapse_retries=N allows up to N+1
        # total attempts (initial + N retries).
        total_attempts = config.max_collapse_retries + 1
        succeeded = False
        for attempt in range(total_attempts):
            logger.log(25, f"=== Training attempt {attempt + 1}/{total_attempts} ===")
            force_fresh = attempt > 0
            attempt_start = time.time()
            result = train_alphazero(seed=attempt, force_fresh=force_fresh, attempt=attempt + 1)
            attempt_end = time.time()

            entry = {
                "attempt": attempt + 1,
                "total_attempts_configured": total_attempts,
                "seed": attempt,
                "fresh_start": force_fresh,
                "config_path": config.path,
                "start_time": attempt_start,
                "end_time": attempt_end,
                "elapsed_seconds": round(attempt_end - attempt_start, 2),
                "outcome": "succeeded" if result["success"] else "collapsed",
                "collapse_iteration": result.get("collapse_iteration"),
                "value_pre_tanh_mean_abs": result.get("value_pre_tanh_mean_abs"),
                "collapse_threshold_pre_tanh": config.collapse_threshold_pre_tanh,
            }
            try:
                with open(retry_log_path, "a") as f:
                    f.write(json.dumps(entry) + "\n")
            except OSError as e:
                logger.log(30, f"Failed to write retry log entry: {e}")

            if result["success"]:
                logger.log(25, f"Training completed successfully on attempt {attempt + 1}.")
                succeeded = True
                break
            logger.log(30, f"Attempt {attempt + 1} ended early due to collapse detection.")

        if not succeeded:
            logger.log(40, f"Training failed on all {total_attempts} attempts (collapse each time). Aborting.")
            raise RuntimeError(f"Collapse detected on all {total_attempts} training attempts.")
    finally:
        if metrics_logger is not None:
            metrics_logger.stop()
